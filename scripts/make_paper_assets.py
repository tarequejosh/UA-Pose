def seed_macros(metrics, arm_ap, macros):
    """Across-seed summary for `full` against the control trained with the same seed.

    Each seed's AP difference is a paired fold mean against its own control, so the SD here is
    between training runs, which the fold SD does not capture.
    """
    results = metrics['results']
    seeds = [s for s in (0, 1, 2) if arm_tag('mbv3', 'full', s) in arm_ap
             and 'diff_mean' in arm_ap[arm_tag('mbv3', 'full', s)].get('gt', {})]
    if not seeds:
        return
    macros.add('SeedCount', str(len(seeds)))
    for box in ('gt', 'det'):
        diffs = np.array([arm_ap[arm_tag('mbv3', 'full', s)][box]['diff_mean'] * 100 for s in seeds])
        sd = f'{np.std(diffs, ddof=1):.2f}' if len(diffs) > 1 else '--'
        macros.add(macro_name('seed', 'dap', box), f'{diffs.mean():+.2f}')
        macros.add(macro_name('seed', 'dap', 'sd', box), sd)
        macros.add(macro_name('seed', 'dap', 'neg', box), f'{int((diffs < 0).sum())} of {len(diffs)}')
        macros.add(macro_name('seed', 'dap', 'range', box), f'{diffs.min():+.2f} to {diffs.max():+.2f}')
    for arm in ('base', 'full'):
        aps = [arm_ap[arm_tag('mbv3', arm, s)]['gt']['AP'] for s in seeds]
        macros.add(macro_name('seed', 'ap', arm), f'{np.mean(aps):.3f}')
    for name, key, label in (('het', 'failure_auroc', 'fa'), ('het', 'occlusion_auroc', 'oa'),
                             ('oks', 'failure_auroc', 'fa')):
        pairs = [results[t]['paired'].get('dist', {}).get(name, {}).get(key)
                 for t in (arm_tag('mbv3', 'full', s) for s in seeds) if t in results]
        pairs = [p for p in pairs if p]
        if len(pairs) != len(seeds):
            continue
        means = np.array([p['mean'] for p in pairs])
        below = sum(p['ci'][1] < 0 for p in pairs)
        above = sum(p['ci'][0] > 0 for p in pairs)
        stem = ('seed', 'd' + label, name, 'minus', 'dist')
        macros.add(macro_name(*stem), f'{means.mean():+.3f}')
        macros.add(macro_name(*stem, 'sd'), f'{np.std(means, ddof=1):.3f}' if len(means) > 1 else '--')
        macros.add(macro_name(*stem, 'below'), f'{below} of {len(pairs)}')
        macros.add(macro_name(*stem, 'above'), f'{above} of {len(pairs)}')


def table_seeds(metrics, sanity, macros, arm_ap=None):
    """Mean and SD over the seeds that actually finished, with the seed count shown."""
    results = metrics['results']
    arm_ap = arm_ap or {}
    lines = ['\\begin{tabular}{lccccccc}', '\\toprule',
             '& & \\multicolumn{2}{c}{AP, val-test, GT} & \\multicolumn{3}{c}{Failure AUROC} & '
             'Occl.\\ AUROC \\\\',
             '\\cmidrule(lr){3-4}\\cmidrule(lr){5-7}\\cmidrule(lr){8-8}',
             'Arm & Seeds & AP & $\\Delta$ & Spread & $\\sigma$ & OKS & Spread \\\\', '\\midrule']
    any_row = False
    for arm in ('base', 'full'):
        tags = [t for t in (arm_tag('mbv3', arm, s) for s in (0, 1, 2)) if t in results]
        if not tags:
            continue
        any_row = True

        def cell(values, digits=3):
            values = [v for v in values if v is not None]
            if not values:
                return '--'
            if len(values) == 1:
                return f'{values[0]:.{digits}f}'
            return f'{np.mean(values):.{digits}f} $\\pm$ {np.std(values, ddof=1):.{digits}f}'

        def signal(tag, name, key='failure_auroc'):
            m = results[tag]['signals'].get(name)
            return m[key] if m else None

        diffs = [arm_ap.get(t, {}).get('gt', {}).get('diff_mean') for t in tags]
        diffs = [d * 100 for d in diffs if d is not None]
        if not diffs:
            delta = '--'
        elif len(diffs) == 1:
            delta = f'{diffs[0]:+.2f}'
        else:
            delta = f'{np.mean(diffs):+.2f} $\\pm$ {np.std(diffs, ddof=1):.2f}'
        lines.append(
            f'{dict(base="Control (KL only)", full="Full head")[arm]} & {len(tags)} & '
            f'{cell([sanity.get(t, {}).get("AP") for t in tags], 4)} & {delta} & '
            f'{cell([signal(t, "dist") for t in tags])} & '
            f'{cell([signal(t, "het") for t in tags])} & '
            f'{cell([signal(t, "oks") for t in tags])} & '
            f'{cell([signal(t, "dist", "occlusion_auroc") for t in tags])} \\\\')
        macros.add(macro_name('num', 'seeds', arm), str(len(tags)))
    lines += ['\\bottomrule', '\\end{tabular}']
    if any_row:
        write_table('seeds', lines)


