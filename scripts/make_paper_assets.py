def load(name):
    path = RESULTS / name
    if not path.exists():
        print(f'[note] missing {path}')
        return None
    return json.loads(path.read_text(encoding='utf-8'))


def write_table(name, lines):
    TABLES.mkdir(parents=True, exist_ok=True)
    text = '\n'.join(real_minus(line) for line in lines)
    (TABLES / f'{name}.tex').write_text(text + '\n', encoding='utf-8')
    print(f'[table] {name}')


def macro_name(*parts):
    """LaTeX command names may only contain letters."""
    digits = dict(zip('0123456789', ['Zero', 'One', 'Two', 'Three', 'Four', 'Five', 'Six',
                                     'Seven', 'Eight', 'Nine']))
    text = ''.join(p[:1].upper() + p[1:] for p in re.split(r'[_\W]+', '_'.join(parts)) if p)
    return ''.join(digits.get(c, c) for c in text)


def real_minus(text):
    """Typeset a negative number with a minus sign, not a hyphen, in text or math mode."""
    return re.sub(r'(?<![\w$.{-])-(?=\.?\d)', r'\\ensuremath{-}', str(text))


class Macros:
    def __init__(self):
        self.values = {}

    def add(self, name, value):
        self.values[name] = value

    def write(self):
        GENERATED.mkdir(parents=True, exist_ok=True)
        lines = ['% Generated by scripts/make_paper_assets.py. Do not edit.']
        lines += [f'\\newcommand{{\\{k}}}{{{real_minus(v)}}}' for k, v in sorted(self.values.items())]
        (GENERATED / 'macros.tex').write_text('\n'.join(lines) + '\n', encoding='utf-8')
        print(f'[macros] {len(self.values)} values')


def bold_if(text, condition):
    return f'\\textbf{{{text}}}' if condition else text


def fmt_ci(ci, digits=3):
    return f'[{ci[0]:.{digits}f}, {ci[1]:.{digits}f}]'


