def table_zeroshot(metrics, macros):
    results = metrics['results']
    lines = ['\\begin{tabular}{lcccccc}', '\\toprule',
             'Signal & Passes & Failure AUROC & AUSE ($\\times 10^{3}$) & Occl.\\ AUROC '
             '& Spearman $\\rho$ & ECE \\\\']
    for tag in ZEROSHOT:
        report = results.get(tag)
        if report is None:
            continue
        signals = report['signals']
        names = [n for n in SIGNAL_ORDER if n in signals]
        best_f = max(signals[n]['failure_auroc'] for n in names)
        best_a = min(signals[n]['ause'] for n in names)
        best_o = max(signals[n]['occlusion_auroc'] for n in names)
        best_r = max(signals[n]['spearman'] for n in names)
        best_e = min(signals[n]['ece'] for n in names)
        lines += ['\\midrule',
                  f'\\multicolumn{{7}}{{l}}{{\\textit{{{MODEL_LABEL[tag]}}}}} \\\\']
        for name in names:
            m = signals[name]
            passes = '20' if name.startswith('mc') else ('2$^\\ast$' if name in ('flip', 'fusion') else '1')
            lines.append(
                f'{SIGNAL_LABEL[name]} & {passes} & '
                f'{bold_if(f"{m["failure_auroc"]:.3f}", m["failure_auroc"] == best_f)} '
                f'{{\\scriptsize {fmt_ci(m["failure_auroc_ci"])}}} & '
                f'{bold_if(f"{m["ause"] * 1e3:.2f}", m["ause"] == best_a)} & '
                f'{bold_if(f"{m["occlusion_auroc"]:.3f}", m["occlusion_auroc"] == best_o)} & '
                f'{bold_if(f"{m["spearman"]:.3f}", m["spearman"] == best_r)} & '
                f'{bold_if(f"{m["ece"]:.3f}", m["ece"] == best_e)} \\\\')
            short = macro_name(tag, name)
            macros.add(macro_name('fa', short), f'{m["failure_auroc"]:.3f}')
            macros.add(macro_name('ause', short), f'{m["ause"] * 1e3:.2f}')
            macros.add(macro_name('oa', short), f'{m["occlusion_auroc"]:.3f}')
            macros.add(macro_name('rho', short), f'{m["spearman"]:.3f}')
    lines += ['\\bottomrule', '\\end{tabular}']
    write_table('zeroshot', lines)

    # Headline paired differences used in the text.
    for tag in ZEROSHOT:
        report = results.get(tag)
        if report is None or 'mc_soft' not in report['paired']:
            continue
        for name in ('dist', 'conf'):
            if name not in report['paired']['mc_soft']:
                continue
            d = report['paired']['mc_soft'][name]['failure_auroc']
            macros.add(macro_name('dfa', tag, name, 'minus', 'mc'),
                       f'{d["mean"]:+.3f} {fmt_ci(d["ci"])}')


