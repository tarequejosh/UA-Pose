        cpu = c['latency'].get('cpu_1thread', {})
        g1, g20 = gpu['single_pass']['median_ms'], gpu['mc_dropout']['median_ms']
        c1, c20 = cpu['single_pass']['median_ms'], cpu['mc_dropout']['median_ms']
        if key.endswith('_plain'):
            # Plain SimCCHead has no MC-Dropout path: both timings are one forward pass.
            lines.append(f'{label} & {c["params_total"] / 1e6:.2f} & {c["flops"] / 1e9:.2f} & '
                         f'{g1:.1f} & -- & -- & {c1:.0f} & -- \\\\')
