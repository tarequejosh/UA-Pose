        lines.append(f'{label} & {c["params_total"] / 1e6:.2f} & {c["flops"] / 1e9:.2f} & '
                     f'{g1:.1f} & {g20:.1f} & {g20 / g1:.1f}$\\times$ & {c1:.0f} & {c20:.0f} \\\\')
        macros.add(macro_name('params', key), f'{c["params_total"] / 1e6:.2f}')
