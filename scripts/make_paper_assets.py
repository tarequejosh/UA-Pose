def figure_qualitative(metrics):
    """Rule-based selection: never hand-picked.

    From val-test instances with >=3 occluded and >=6 visible labelled joints and box
    side >=150 px, sorted by id, take the instances with the four largest gaps between
    occluded and visible mean error. These are the informative failures by construction.
    """
    path = DUMPS / 'zs_simcc_mbv3.npz'
    if not path.exists():
        return
    sys.path.insert(0, str(ROOT))
    import importlib.util
    spec = importlib.util.spec_from_file_location(
        'analysis', ROOT / 'ua_pose' / 'evaluation' / 'analysis.py')
    analysis = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(analysis)

    ann = json.loads((ROOT / 'data/coco/annotations/person_keypoints_val2017.json')
                     .read_text(encoding='utf-8'))
    files = {im['id']: im['file_name'] for im in ann['images']}
    _, test_ids = analysis.split_images(list(files))
    test_ids = set(test_ids.tolist())

    with np.load(path) as data:
        d = {k: data[k] for k in data.files}
    scale = np.sqrt(d['bbox_xywh'][:, 2] * d['bbox_xywh'][:, 3]).clip(1)
    err = np.linalg.norm(d['keypoints'] - d['gt_keypoints'], axis=-1) / scale[:, None]
    candidates = []
    for i in range(len(d['img_id'])):
        vis = d['gt_vis'][i]
        if int(d['img_id'][i]) not in test_ids or d['iscrowd'][i]:
            continue
        if (vis == 1).sum() < 3 or (vis == 2).sum() < 6 or min(d['bbox_xywh'][i, 2:]) < 150:
            continue
        gap = err[i][vis == 1].mean() - err[i][vis == 2].mean()
        candidates.append((gap, i))
    picks = [i for _, i in sorted(candidates, reverse=True)[:4]]

    skeleton = [(15, 13), (13, 11), (16, 14), (14, 12), (11, 12), (5, 11), (6, 12),
                (5, 6), (5, 7), (6, 8), (7, 9), (8, 10)]
    spread = d['u_dist'][d['gt_vis'] > 0]
    low, high = np.percentile(spread, [33, 90])
    tiers = [('Low spread', '#86b6ef', 14), ('Medium', '#2a78d6', 26), ('High', '#eb6834', 44)]

    fig, axes = plt.subplots(1, 4, figsize=(7.2, 2.5))
    for ax, i in zip(axes, picks):
        img = cv2.cvtColor(
            cv2.imread(str(ROOT / 'data/coco/val2017' / files[int(d['img_id'][i])])),
            cv2.COLOR_BGR2RGB)
        x, y, w, h = d['bbox_xywh'][i]
        pad = 0.15 * max(w, h)
        x1, y1 = int(max(0, x - pad)), int(max(0, y - pad))
        x2, y2 = int(min(img.shape[1], x + w + pad)), int(min(img.shape[0], y + h + pad))
        ax.imshow(img[y1:y2, x1:x2])
        kpt, gt, vis, unc = (d['keypoints'][i], d['gt_keypoints'][i], d['gt_vis'][i], d['u_dist'][i])
        for a, b in skeleton:
            if vis[a] > 0 and vis[b] > 0:
                ax.plot([kpt[a, 0] - x1, kpt[b, 0] - x1], [kpt[a, 1] - y1, kpt[b, 1] - y1],
                        color='white', lw=1.0, alpha=0.8)
        for j in range(17):
            if vis[j] == 0:
                continue
            tier = 0 if unc[j] < low else (1 if unc[j] < high else 2)
            ax.plot([kpt[j, 0] - x1, gt[j, 0] - x1], [kpt[j, 1] - y1, gt[j, 1] - y1],
                    color='#ffe14d', lw=0.9)
            _, color, size = tiers[tier]
            ax.scatter(kpt[j, 0] - x1, kpt[j, 1] - y1, s=size, c=color, edgecolors='white',
                       linewidths=0.6, zorder=4, marker='o' if vis[j] == 2 else 's')
        ax.set_xlim(0, x2 - x1)
        ax.set_ylim(y2 - y1, 0)
        ax.set_axis_off()
    handles = [plt.Line2D([], [], marker='o', ls='none', color=c, ms=np.sqrt(s),
                          markeredgecolor='white', label=l) for l, c, s in tiers]
    handles.append(plt.Line2D([], [], marker='s', ls='none', color=MUTED, ms=4.5, label='Occluded (v=1)'))
    handles.append(plt.Line2D([], [], color='#d9b600', lw=1.2, label='Error to ground truth'))
    fig.legend(handles=handles, loc='lower center', ncol=5, bbox_to_anchor=(0.5, -0.07))
    fig.tight_layout(pad=0.3)
    save(fig, 'qualitative')


